use std::collections::HashSet;

use super::{Preview, Workspace, preview};
use zigzag::{design::Design, params::Kind};

fn same_stitch_plan(left: &Design, right: &Design) -> bool {
    left.blocks.len() == right.blocks.len() && left.blocks.iter().zip(&right.blocks).all(|(a, b)| {
        a.color == b.color && a.runs.len() == b.runs.len() && a.runs.iter().zip(&b.runs).all(|(x, y)| {
            x.trim_before == y.trim_before && x.pts.len() == y.pts.len()
                && x.pts.iter().zip(&y.pts).all(|(p, q)| {
                    // JSON round trips can change the last floating-point digit.
                    p.dist(*q) < 1e-6 && p.x.round() == q.x.round() && p.y.round() == q.y.round()
                })
        })
    })
}

pub(super) fn apply(workspace: &mut Workspace, index: usize, color: [u8; 3]) -> Result<Preview, String> {
    let current = workspace.current.as_ref().ok_or("Open artwork first")?;
    let previous = current.blocks.get(index).ok_or("Thread block unavailable")?.color;
    if previous == color {
        return Ok(preview(current));
    }
    let Some(source) = workspace.source.as_ref() else {
        workspace.checkpoint_named("Change thread color");
        let design = workspace.current.as_mut().ok_or("Open artwork first")?;
        design.blocks[index].color = color;
        return Ok(preview(design));
    };

    // The v1 native file retains the actual points, but does not serialize
    // the planner's ownership map. Verify any reconstructed mapping first.
    let rebuilt;
    let owners = if current.block_shapes.len() == current.blocks.len() {
        &current.block_shapes
    } else {
        rebuilt = source.plan();
        if !same_stitch_plan(current, &rebuilt) {
            return Err("The saved stitches differ from the artwork plan. This thread cannot be mapped back to its artwork.".into());
        }
        &rebuilt.block_shapes
    };
    let selected: HashSet<usize> = owners.get(index).ok_or("Thread ownership unavailable")?.iter().copied().collect();
    if selected.is_empty() {
        return Err("No editable objects are mapped to this thread.".into());
    }
    if owners.iter().enumerate().any(|(i, shapes)| i != index && shapes.iter().any(|s| selected.contains(s))) {
        return Err("This object sews in multiple stages. A stage-specific thread change cannot be saved to its artwork.".into());
    }

    let mut updated = source.clone();
    for &i in &selected {
        let shape = updated.shapes.get_mut(i).ok_or("Thread ownership refers to missing artwork")?;
        let staged_satin = shape.params.kind == Some(Kind::Satin)
            && shape.params.colors.as_ref().is_some_and(|colors| colors.len() >= 2);
        if shape.color != previous || shape.params.kind == Some(Kind::Tartan) || staged_satin {
            return Err("This thread is generated by the object's stitch pattern. A single block change cannot be saved to its artwork.".into());
        }
        shape.color = color;
    }
    let design = updated.plan();
    if design.stitch_count() == 0 {
        return Err("The new thread plan contains no stitches.".into());
    }
    let result = preview(&design);
    workspace.checkpoint_named("Change thread color");
    workspace.source = Some(updated);
    workspace.current = Some(design);
    Ok(result)
}

pub(super) fn replace_color(workspace:&mut Workspace,previous:[u8;3],color:[u8;3])->Result<Preview,String>{
 let current=workspace.current.as_ref().ok_or("Open artwork first")?;
 if previous==color{return Ok(preview(current))}
 let mut expected=current.clone();
 let mut found=false;
 for b in &mut expected.blocks {if b.color==previous{b.color=color;found=true}}
 if !found{return Err("Color no longer exists in the design".into())}
 if let Some(source)=workspace.source.as_ref(){
   let mut updated=source.clone();
   for shape in &mut updated.shapes{
     if shape.color==previous{shape.color=color;}
     if let Some(colors)=shape.params.colors.as_mut(){for entry in colors.iter_mut(){if *entry==previous{*entry=color;}}}
   }
   let design=updated.plan();
   let normalize=|d:&Design|{let mut blocks:Vec<([u8;3],Vec<(bool,Vec<(i64,i64)>)>)>=Vec::new();for b in &d.blocks{if blocks.last().is_none_or(|last|last.0!=b.color){blocks.push((b.color,Vec::new()))}blocks.last_mut().unwrap().1.extend(b.runs.iter().map(|r|(r.trim_before,r.pts.iter().map(|p|(p.x.round() as i64,p.y.round() as i64)).collect::<Vec<_>>())));}blocks};
   if normalize(&design)!=normalize(&expected){return Err("This color is controlled by a special stitch pattern or changing it would alter sewing order. Edit the specific object instead.".into())}
   let result=preview(&design);workspace.checkpoint_named("Replace design color");workspace.source=Some(updated);workspace.current=Some(design);Ok(result)
 }else{let result=preview(&expected);workspace.checkpoint_named("Replace design color");workspace.current=Some(expected);Ok(result)}
}
pub(super) fn map_blocks(workspace:&mut Workspace,original:&[[u8;3]],colors:&[[u8;3]])->Result<Preview,String>{
 let current=workspace.current.as_ref().ok_or("Open a design first")?;
 if colors.len()!=current.blocks.len()||original.len()!=colors.len()||!current.blocks.iter().zip(original).all(|(b,c)|b.color==*c){return Err("The design changed. Refresh the mapping.".into())}
 let mut expected=current.clone();
 for (b,c) in expected.blocks.iter_mut().zip(colors){b.color=*c}
 if let Some(source)=workspace.source.as_ref(){
   let rebuilt=source.plan();
   if !same_stitch_plan(current,&rebuilt){return Err("The editable artwork no longer matches the stitch stream.".into())}
   if rebuilt.block_shapes.len()!=colors.len(){return Err("Missing thread ownership".into())}
   let mut updated=source.clone();
   let mut assignments=std::collections::HashMap::new();
   for (i,owners) in rebuilt.block_shapes.iter().enumerate(){
     if owners.is_empty(){return Err("Missing thread ownership".into())}
     for &owner in owners{
       let shape=updated.shapes.get(owner).ok_or("Missing artwork object")?;
       if shape.color!=original[i]||shape.params.kind==Some(Kind::Tartan)||shape.params.colors.is_some(){return Err("A special stitch pattern needs individual editing.".into())}
       if assignments.insert(owner,colors[i]).is_some_and(|old|old!=colors[i]){return Err("An object uses conflicting mapped colors.".into())}
     }
   }
   for (i,color) in assignments{updated.shapes[i].color=color;}
   let planned=updated.plan();
   if !same_stitch_plan(&expected,&planned){return Err("Mapping would change sewing order or stitch geometry. Choose distinct colors for adjacent blocks or edit them individually.".into())}
   let result=preview(&planned);workspace.checkpoint_named("Map reference colors");workspace.source=Some(updated);workspace.current=Some(planned);Ok(result)
 }else{let result=preview(&expected);workspace.checkpoint_named("Map reference colors");workspace.current=Some(expected);Ok(result)}
}
#[cfg(test)]
mod tests {
    use super::*;
    use crate::Project;
    use std::sync::Mutex;
    use zigzag::document::Document;

    fn design() -> Workspace {
        let svg = r##"<svg xmlns="http://www.w3.org/2000/svg" width="50mm" height="10mm" viewBox="0 0 50 10">
            <path id="one" fill="#882211" d="M0 0H8V8H0Z"/>
            <path id="two" fill="#882211" d="M12 0H20V8H12Z"/>
            <path id="three" fill="#245680" d="M24 0H32V8H24Z"/>
            <path id="four" fill="#882211" d="M36 0H44V8H36Z"/>
        </svg>"##;
        let source = Document::from_svg(svg, "thread sequence", None).unwrap();
        Workspace { current: Some(source.plan()), source: Some(source), ..Workspace::default() }
    }

    fn reopen(workspace: &Workspace) -> Workspace {
        let project = Project::capture(workspace, 100.0, 100.0, "pes".into()).unwrap().unwrap();
        let bytes = serde_json::to_vec(&project).unwrap();
        let saved: Project = serde_json::from_slice(&bytes).unwrap();
        let target = Mutex::new(Workspace::default());
        saved.restore(&target).unwrap();
        target.into_inner().unwrap()
    }

    #[test]
    fn reference_mapping_preserves_commands_and_is_atomic() {
        let mut work=design();
        work.source=None;
        let original:Vec<_>=work.current.as_ref().unwrap().blocks.iter().map(|b|b.color).collect();
        let before=zigzag::formats::dst::write_dst(work.current.as_ref().unwrap());
        let mapped:Vec<_>=original.iter().map(|c|[c[2],c[0],c[1]]).collect();
        assert!(map_blocks(&mut work,&original,&[]).is_err());
        assert!(work.undo.is_empty());
        map_blocks(&mut work,&original,&mapped).unwrap();
        assert_eq!(work.undo.len(),1);
        assert_eq!(before,zigzag::formats::dst::write_dst(work.current.as_ref().unwrap()));
        assert_eq!(work.current.as_ref().unwrap().blocks.iter().map(|b|b.color).collect::<Vec<_>>(),mapped);
        assert!(map_blocks(&mut work,&original,&mapped).is_err());
        assert_eq!(work.undo.len(),1);
    }
    #[test]
    fn replaces_repeated_colors_with_one_undo_step(){
      let mut work=design();let before=work.source.as_ref().unwrap().to_svg().unwrap();
      let previous=[0x88,0x22,0x11];let next=[90,70,150];
      replace_color(&mut work,previous,next).unwrap();
      assert_eq!(work.undo.len(),1);
      assert_eq!(work.undo[0].1.as_ref().unwrap().to_svg().unwrap(),before);
      assert!(work.current.as_ref().unwrap().blocks.iter().all(|b|b.color!=previous));
      assert!(same_stitch_plan(&reopen(&work).source.unwrap().plan(),work.current.as_ref().unwrap()));
    }
    #[test]
    fn recolors_only_objects_in_the_selected_block_and_saves_editable_source() {
        let mut work = reopen(&design());
        let before = work.source.as_ref().unwrap().to_svg().unwrap();
        let color = [128, 95, 180];
        apply(&mut work, 0, color).unwrap();
        assert_eq!(work.undo.last().unwrap().1.as_ref().unwrap().to_svg().unwrap(), before);
        let restored = reopen(&work);
        let source = restored.source.unwrap();
        let colors: Vec<_> = source.shapes.iter().map(|s| s.color).collect();
        assert_eq!(colors, vec![color, color, [0x24, 0x56, 0x80], [0x88, 0x22, 0x11]]);
        assert!(same_stitch_plan(&source.plan(), &restored.current.unwrap()));
    }

    #[test]
    fn recolor_into_an_adjacent_color_is_reconstructible_on_reopen() {
        let mut work = design();
        apply(&mut work, 0, [0x24, 0x56, 0x80]).unwrap();
        let mut restored = reopen(&work);
        apply(&mut restored, 0, [60, 0, 80]).unwrap();
        assert_eq!(restored.source.unwrap().shapes.len(), 4);
    }

    #[test]
    fn refuses_a_single_applique_stage_without_changing_history_or_artwork() {
        let mut work = design();
        let source = work.source.as_mut().unwrap();
        source.shapes[0].params.kind = Some(Kind::Applique);
        work.current = Some(source.plan());
        let before = source.to_svg().unwrap();
        let encoded = zigzag::formats::dst::write_dst(work.current.as_ref().unwrap());
        assert!(apply(&mut work, 0, [5, 6, 7]).is_err());
        assert_eq!(before, work.source.unwrap().to_svg().unwrap());
        assert_eq!(encoded, zigzag::formats::dst::write_dst(&work.current.unwrap()));
        assert!(work.undo.is_empty());
    }

    #[test]
    fn stale_stitches_preserve_the_existing_plan_and_source_less_files_still_recolor() {
        let mut work = reopen(&design());
        work.current.as_mut().unwrap().blocks[0].runs[0].pts[0].x += 10.0;
        let encoded = zigzag::formats::dst::write_dst(work.current.as_ref().unwrap());
        assert!(apply(&mut work, 0, [1, 2, 3]).is_err());
        assert!(work.undo.is_empty());
        work.source = None;
        apply(&mut work, 0, [1, 2, 3]).unwrap();
        assert_eq!(encoded, zigzag::formats::dst::write_dst(work.current.as_ref().unwrap()));
        assert_eq!(work.current.unwrap().blocks[0].color, [1, 2, 3]);
    }
}
